const TRANSACTION_SOURCES = [
  "Sales Module",
  "Procurement Module",
  "Payroll",
  "Bank Feed",
  "Manual Journal",
  "Inventory Module",
];

function buildTransactions(): Transaction[] {
  const rng = createRng(20260610);
  const postable = accounts.filter((account) => account.subType !== "Header");

  return Array.from({ length: 148 }, (_, index) => {
    const account = postable[index % postable.length];
    const category = TRANSACTION_CATEGORIES[index % TRANSACTION_CATEGORIES.length];
    const amount = Math.round(moneyBetween(rng, 1840, 1284500) * 100) / 100;
    const isDebit = index % 2 === 0;

    return {
      id: `TXN-${480200 + index}`,
      reference: `TXN-${480200 + index}`,
      date: isoDate(-intBetween(rng, 0, 210)),
      description: `${category} — ${pick(rng, ["batch posting", "monthly run", "reconciled entry", "allocation", "settlement"])} ${index + 1}`,
      category,
      accountCode: account.code,
      accountName: account.name,
      debit: isDebit ? amount : 0,
      credit: isDebit ? 0 : amount,
      currency: "ZAR",
      status: weighted(rng, [
        ["Posted", 52],
        ["Reconciled", 30],
        ["Pending", 14],
        ["Void", 4],
      ] as const),
      source: TRANSACTION_SOURCES[index % TRANSACTION_SOURCES.length],
    };
  });
}

export const transactions: Transaction[] = buildTransactions();

